// T translates key into locale, falling back to English, then to the key
// itself if truly undeclared — a missing translation should be visible and
// debuggable, never a blank string or a crash.
func T(locale, key string) string {
	if m, ok := catalog[locale]; ok {
		if v, ok := m[key]; ok {
			return v
		}
	}
	if v, ok := catalog[Default][key]; ok {
		return v
	}
	return key
}
