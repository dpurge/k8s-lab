package i18n

const Default = "en"

// Locale is one selectable site-translation option.
type Locale struct {
	Code string
	Name string
}

// Locales lists every selectable site language, for the profile page's
// dropdown. Order is display order.
var Locales = []Locale{
	{Code: "en", Name: "English"},
	{Code: "pl", Name: "Polski"},
}

// IsValid reports whether code is one of the selectable locales.
func IsValid(code string) bool {
	for _, l := range Locales {
		if l.Code == code {
			return true
		}
	}
	return false
}

